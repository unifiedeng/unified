def model_bodies(master):
    """Bodies the drawing views actually display: the solids-only reference
    set if one exists (tool/construction bodies live outside it)."""
    try:
        for rs in master.GetAllReferenceSets():
            if rs.Name.upper() not in ("MODEL", "SOLID", "BODY"):
                continue
            for getter in ("AskAllDirectMembers", "GetAllDirectMembers",
                           "AskMembersInReferenceSet", "GetMembers"):
                if hasattr(rs, getter):
                    try:
                        members = getattr(rs, getter)()
                        bodies = [m for m in members if isinstance(m, NXOpen.Body)]
                        if bodies:
                            say("Analyzing %d body(ies) from refset %s"
                                % (len(bodies), rs.Name))
                            return bodies
                    except Exception:
                        continue
    except Exception:
        pass
    bodies = [b for b in master.Bodies]
    if len(bodies) > 1:
        rep("WARNING: %d bodies, no solids refset — analyzing all (tool "
            "remnants may pollute the dimension scheme)" % len(bodies))
    return bodies


class Geometry(object):
    def __init__(self, master):
        self.lo = [1e30] * 3
        self.hi = [-1e30] * 3
        self.lin_edges = []      # (edge, pa, pb, unit_dir)
        self.circles = []        # dict: edge, center(3), axis(int 0/1/2), r
        verts = [[], [], []]
        self.bodies = model_bodies(master)
        for b in self.bodies:
            for e in b.GetEdges():
                try:
                    vs = e.GetVertices()
                except Exception:
                    vs = []
                for p in vs:
                    for i, c in enumerate((p.X, p.Y, p.Z)):
                        self.lo[i] = min(self.lo[i], c)
                        self.hi[i] = max(self.hi[i], c)
                try:
                    et = e.SolidEdgeType
                except Exception:
                    continue
                if et == NXOpen.Edge.EdgeType.Linear and len(vs) == 2:
                    a, b2 = vs
                    d = [b2.X - a.X, b2.Y - a.Y, b2.Z - a.Z]
                    ln = math.sqrt(sum(c * c for c in d))
                    if ln > 1e-9:
                        self.lin_edges.append((e, a, b2, [c / ln for c in d]))
                        # coordinate levels only from linear-edge endpoints
                        # (circle seam vertices are parametric noise)
                        for p in vs:
                            for i, c in enumerate((p.X, p.Y, p.Z)):
                                verts[i].append(c)
                elif et == NXOpen.Edge.EdgeType.Circular:
                    self.n_circ = getattr(self, "n_circ", 0) + 1
                    try:
                        c = self._fit_circle(e)
                    except Exception:
                        say("circle fit raised on edge %d:\n%s"
                            % (e.Tag, traceback.format_exc().splitlines()[-1]))
                        c = None
                    if c:
                        self.circles.append(c)
                    else:
                        self.n_circ_fail = getattr(self, "n_circ_fail", 0) + 1
        for c in self.circles:
            for i in range(3):
                self.lo[i] = min(self.lo[i], c["center"][i] - (c["r"] if i != c["axis"] else 0))
                self.hi[i] = max(self.hi[i], c["center"][i] + (c["r"] if i != c["axis"] else 0))
        self.ext = [self.hi[i] - self.lo[i] for i in range(3)]
        tol = max(self.ext) * 1e-3 + 1e-6
        self.levels = [cluster(verts[i], tol) for i in range(3)]
        # planar faces (axis-aligned): (axis, coord, approx_area) for datum choice
        self.planar_faces = []
        for b in self.bodies:
            for f in b.GetFaces():
                try:
                    if f.SolidFaceType != NXOpen.Face.FaceType.Planar:
                        continue
                    pts = []
                    for e in f.GetEdges():
                        try:
                            pts.extend(e.GetVertices())
                        except Exception:
                            pass
                    if len(pts) < 3:
                        continue
                    for axis in range(3):
                        cs = [(p.X, p.Y, p.Z)[axis] for p in pts]
                        if max(cs) - min(cs) < tol:
                            o1, o2 = [i for i in range(3) if i != axis]
                            e1 = [(p.X, p.Y, p.Z)[o1] for p in pts]
                            e2 = [(p.X, p.Y, p.Z)[o2] for p in pts]
                            area = (max(e1) - min(e1)) * (max(e2) - min(e2))
                            if area > tol * tol:
                                self.planar_faces.append(
                                    (axis, sum(cs) / len(cs), area))
                            break
                except Exception:
                    pass

    def _fit_circle(self, e):
        """Fit center/axis/radius from points on the circular edge."""
        pts = None
        try:
            pts = e.GetLocations()
        except Exception:
            pass
        if not pts or len(pts) < 3:
            return None
        def xyz(p):
            for attr in ("X", None):
                if attr and hasattr(p, "X"):
                    return (p.X, p.Y, p.Z)
            for attr in ("Point", "Location", "Position"):
                q = getattr(p, attr, None)
                if q is not None and hasattr(q, "X"):
                    return (q.X, q.Y, q.Z)
            raise AttributeError("no point in %s: %s" % (type(p), dir(p)))
        # CurveLocation.Type: 2 = center, others are on-curve points
        center = None
        rim = []
        for p in pts:
            q = xyz(p)
            t = getattr(p, "Type", None)
            try:
                is_center = int(str(t)) == 2
            except Exception:
                is_center = "2" in str(t) or "enter" in str(t)
            if is_center:
                center = q
            else:
                rim.append(q)
        if center is None or len(rim) < 2:
            return None
        radials = [[q[i] - center[i] for i in range(3)] for q in rim]
        # axis = normal of rim plane: largest cross product of radius vectors
        best_n, best_ln = None, 0.0
        for i in range(len(radials)):
            for j in range(i + 1, len(radials)):
                v1, v2 = radials[i], radials[j]
                n = [v1[1] * v2[2] - v1[2] * v2[1],
                     v1[2] * v2[0] - v1[0] * v2[2],
                     v1[0] * v2[1] - v1[1] * v2[0]]
                ln = math.sqrt(sum(c * c for c in n))
                if ln > best_ln:
                    best_n, best_ln = n, ln
        if best_ln < 1e-12:
            return None
        n = [abs(c / best_ln) for c in best_n]
        axis = n.index(max(n))
        if n[axis] < 0.99:
            return None            # not axis-aligned; reported as uncovered later
        r = sum(math.sqrt(sum(v * v for v in rv)) for rv in radials) / len(radials)
        return {"edge": e, "center": list(center), "axis": axis, "r": r}


def group_holes(geom):
    """Group coaxial circles into hole/boss features."""
    groups = {}
    for c in geom.circles:
        ax = c["axis"]
        o1, o2 = [i for i in range(3) if i != ax]
        key = (ax, round(c["center"][o1], 2), round(c["center"][o2], 2), round(c["r"], 2))
        groups.setdefault(key, []).append(c)
    holes = []
    for (ax, k1, k2, r), cs in sorted(groups.items()):
        zs = [c["center"][ax] for c in cs]
        span = max(zs) - min(zs) if len(cs) > 1 else 0.0
        through = span >= geom.ext[ax] - max(geom.ext) * 1e-3
        holes.append({"axis": ax, "center": cs[0]["center"], "r": r,
                      "span": span, "through": through,
                      "edge": max(cs, key=lambda c: c["center"][ax])["edge"]})
    return holes


# ------------------------------------------------- 1b. turned-part features
# Parts of revolution (flanges, bosses, turned shafts) do not follow the
# prismatic rectangular-coordinate scheme: their outer profile is circular,
# so there are no linear coordinate levels and no planar datum faces
# perpendicular to the transverse axes. They are dimensioned instead by
# concentric diameters, one axial thickness, and a bolt-circle-located hole
# pattern (ASME Y14.5 section 5 diameters; repeated features by "nX").
def classify_part(geom):
    """Return ("turned", axis) if the outer boundary is a circle centered on
    the part (a body of revolution about that axis), else ("prismatic", None).
    Test: a circle whose diameter fills both transverse extents and is
    centered — i.e. the silhouette in that plane is round, not rectangular."""
    tol = max(geom.ext) * 1e-3 + 1e-6
    for axis in range(3):
        o1, o2 = [i for i in range(3) if i != axis]
        if geom.ext[o1] <= tol or geom.ext[o2] <= tol:
            continue
        mid1 = (geom.lo[o1] + geom.hi[o1]) / 2
        mid2 = (geom.lo[o2] + geom.hi[o2]) / 2
        for c in geom.circles:
            if c["axis"] != axis:
                continue
            near = 0.02 * max(geom.ext[o1], geom.ext[o2]) + tol
            if abs(2 * c["r"] - geom.ext[o1]) <= near and \
               abs(2 * c["r"] - geom.ext[o2]) <= near and \
               abs(c["center"][o1] - mid1) <= near and \
               abs(c["center"][o2] - mid2) <= near:
                return "turned", axis
    return "prismatic", None


def build_turned_features(geom, axis):
    """Decompose a turned part about `axis` into:
      concentric[]  -- distinct diameters centered on the axis (OD, registers,
                       bores, counterbores), each dimensioned once as a diameter
      holes[]       -- off-axis coaxial-circle stacks (through/blind, possibly
                       counterbored), grouped into patterns of identical features
    Coaxial circles at one transverse location merge into one feature; the
    widest diameter opening at the part's top face is its counterbore."""
    o1, o2 = [i for i in range(3) if i != axis]
    tol = max(geom.ext) * 1e-3 + 1e-6
    ctol = 5 * tol
    axis_mid1 = (geom.lo[o1] + geom.hi[o1]) / 2
    axis_mid2 = (geom.lo[o2] + geom.hi[o2]) / 2
    top = geom.hi[axis]

    # group every axis-parallel circle by its transverse (o1,o2) center
    groups = {}
    for c in geom.circles:
        if c["axis"] != axis:
            continue
        key = (round(c["center"][o1] / ctol), round(c["center"][o2] / ctol))
        groups.setdefault(key, []).append(c)

    def steps(cs):
        """Distinct diameters in a coaxial stack, each with its axial reach:
        [{r, dia, z_hi, z_lo, span, through, depth_from_top}], widest first."""
        by_r = {}
        for c in cs:
            by_r.setdefault(round(c["r"] / (2 * tol)), []).append(c)
        out = []
        for _, rc in by_r.items():
            zs = [c["center"][axis] for c in rc]
            r = sum(c["r"] for c in rc) / len(rc)
            z_hi, z_lo = max(zs), min(zs)
            span = z_hi - z_lo
            through = span >= geom.ext[axis] - max(geom.ext) * 1e-3
            out.append({"r": r, "dia": 2 * r, "z_hi": z_hi, "z_lo": z_lo,
                        "span": span, "through": through,
                        "depth_from_top": top - z_lo,
                        "edge": max(rc, key=lambda c: c["center"][axis])["edge"]})
        out.sort(key=lambda s: -s["r"])
        return out

    concentric, holes = [], []
    for (k1, k2), cs in groups.items():
        c0 = cs[0]["center"]
        on_axis = abs(c0[o1] - axis_mid1) <= ctol and abs(c0[o2] - axis_mid2) <= ctol
        st = steps(cs)
        if on_axis:
            for s in st:
                concentric.append(s)
        else:
            # composite hole: the narrowest step is the pilot; a wider step
            # opening at either end face is a counterbore/spotface. The whole
            # passage is THRU when the union of steps spans the full thickness.
            main = min(st, key=lambda s: s["r"])
            union_lo = min(s["z_lo"] for s in st)
            union_hi = max(s["z_hi"] for s in st)
            through = (union_hi - union_lo) >= geom.ext[axis] - max(geom.ext) * 1e-3
            main["through"] = through
            main["depth"] = 0.0 if through else union_hi - main["z_lo"]
            # which face the pilot opens on (nearest end face)
            main_top = abs(main["z_hi"] - geom.hi[axis]) <= abs(main["z_lo"] - geom.lo[axis])
            cbore, cbore_top = None, None
            for s in st:
                if s["r"] <= main["r"] + tol:
                    continue
                opens_top = abs(s["z_hi"] - geom.hi[axis]) <= 2 * tol
                opens_bot = abs(s["z_lo"] - geom.lo[axis]) <= 2 * tol
                if (opens_top or opens_bot) and (cbore is None or s["r"] > cbore["r"]):
                    cbore, cbore_top = s, opens_top
            if cbore:
                cbore["depth"] = cbore["z_hi"] - cbore["z_lo"]
            holes.append({"center": list(c0), "o1": o1, "o2": o2,
                          "radius": math.hypot(c0[o1] - axis_mid1, c0[o2] - axis_mid2),
                          "main": main, "cbore": cbore, "steps": st,
                          "far_side": cbore is not None and cbore_top != main_top,
                          "edge": main["edge"]})
    # one diameter dim per distinct concentric diameter (widest = OD)
    concentric.sort(key=lambda s: -s["r"])
    dedup, seen_d = [], []
    for cc in concentric:
        if not any(abs(cc["dia"] - d) <= 2 * tol for d in seen_d):
            dedup.append(cc)
            seen_d.append(cc["dia"])
    concentric = dedup

    # group holes into patterns by signature (main dia + through/depth + cbore)
    def sig(h):
        m, cb = h["main"], h["cbore"]
        return (round(m["dia"], 3), m["through"], round(m.get("depth", 0), 2),
                round(cb["dia"], 3) if cb else 0,
                round(cb.get("depth", 0), 2) if cb else 0, h["far_side"])

    patterns = {}
    for h in holes:
        patterns.setdefault(sig(h), []).append(h)
    pats = []
    for s, hs in patterns.items():
        radii = [h["radius"] for h in hs]
        bolt_circle = len(hs) > 1 and (max(radii) - min(radii)) <= 0.02 * max(geom.ext) + tol
        pats.append({"holes": hs, "count": len(hs),
                     "bc_dia": 2 * (sum(radii) / len(radii)) if bolt_circle else None,
                     "bolt_circle": bolt_circle})
    pats.sort(key=lambda p: -p["count"])
    return {"axis": axis, "o1": o1, "o2": o2, "concentric": concentric,
            "patterns": pats, "top": top}

